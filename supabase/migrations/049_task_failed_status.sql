-- ============================================================
-- Migration 049: статус "Не завершено" для задач
-- ============================================================
-- Бизнес-запрос: сотрудник, взявший задачу в работу, должен иметь
-- возможность пометить "не смог завершить" с указанием причины —
-- отдельно от обычного rejectHandover (тот возвращает задачу в очередь
-- без исполнителя). Здесь исполнитель остаётся, но статус сигнализирует
-- директору о провале выполнения.
--
-- Решение: добавить значение 'failed' в enum task_status. Причина
-- пишется в существующую колонку employee_note. Триггер 048 уже
-- сбрасывает completed_at, потому что условие "OLD.status = 'done'"
-- здесь не выполнится — переход in_progress → failed его не задевает,
-- и completed_at остаётся NULL для failed (как и должно).
-- ============================================================

ALTER TYPE task_status ADD VALUE IF NOT EXISTS 'failed';
