-- ============================================================
-- Migration 072: группировка прямых поручений (batch_id)
-- ============================================================
-- Контекст: одно поручение, выданное нескольким сотрудникам через
-- createDirectTaskBulk, физически создаёт N строк direct_tasks — по одной
-- на исполнителя (у каждого свой status/accepted_at/employee_note). В журнале
-- директора это выглядело как N одинаковых карточек.
--
-- Решение: помечаем строки одной bulk-выдачи общим batch_id. UI группирует
-- их в одну карточку с рядом исполнителей, сохраняя независимый прогресс
-- каждого. Одиночные поручения остаются с batch_id IS NULL и рисуются как
-- раньше.
--
-- RLS не трогаем: batch_id — обычная колонка существующей таблицы, её
-- покрывают действующие политики direct_tasks (см. 042/043/047).
-- ============================================================

ALTER TABLE direct_tasks ADD COLUMN IF NOT EXISTS batch_id UUID;

-- Частичный индекс — нужен только для группировки непустых батчей.
CREATE INDEX IF NOT EXISTS idx_direct_tasks_batch
  ON direct_tasks(batch_id)
  WHERE batch_id IS NOT NULL;

COMMENT ON COLUMN direct_tasks.batch_id IS
  'Общий идентификатор пачки: строки одной bulk-выдачи поручения нескольким исполнителям. NULL — одиночное поручение.';
